import { z } from 'zod';
export * from './knowledge.ts';
export * from './browser-accounts.ts';
export * from './auth.ts';
export * from './account.ts';
export * from './operations.ts';
export const UsernameSchema=z.string().max(64).transform(s=>s.normalize('NFKC').trim().toLowerCase()).pipe(z.string().regex(/^[a-z0-9_][a-z0-9_-]{2,31}$/));
export const LoginSchema=z.strictObject({username:z.union([UsernameSchema,z.string().trim().pipe(z.email().max(254))]),password:z.string().min(1).max(128)});
export const RegisterSchema=z.strictObject({username:UsernameSchema,password:z.string().min(12).max(128)});
export const PersonalRecordKindSchema=z.enum(['draft','bookmark','history']);
export const PersonalRecordKeySchema=z.string().min(1).max(160);
export type PersonalRecordKind=z.infer<typeof PersonalRecordKindSchema>;
export type PersonalRecordDto={kind:PersonalRecordKind;key:string;value:string;updatedAt:string};
export const ProfileUpdateSchema = z.strictObject({nickname:z.string().trim().min(1).max(40)});
export const SaveRevisionSchema = z.strictObject({title:z.string().trim().min(1).max(160),markdown:z.string().min(1).max(500000),baseRevisionId:z.string().min(1).nullable(),changeNote:z.string().max(500),idempotencyKey:z.string().min(8).max(100)});
export const UploadReservationSchema = z.strictObject({sizeBytes:z.number().int().positive().max(100000000),mime:z.string().min(1).max(100),filename:z.string().trim().min(1).max(255),key:z.string().min(8).max(100)});
export type SaveRevisionInput=z.infer<typeof SaveRevisionSchema>;
export type Actor={userId:string;kind:'guest'|'member';platformRoles:string[]};
export type RequestContext={actor:Actor|null;requestId:string};
export type ApiProblem={code:string;message:string;requestId:string;details?:unknown};
export type CursorPage<T>={items:T[];nextCursor:string|null};
export type WikiRevisionDto={id:string;pageId:string;title:string;markdown:string;changeNote:string;authorAlias:string;createdAt:string;previousRevisionId:string|null};
export type WikiPageMetadata={id:string;slug:string;communityId:string;communitySlug:string;communityName:string;protected:boolean};
export type RevisionDiff={blocks:{kind:'equal'|'removed'|'added';text:string}[];attachments:{added:string[];removed:string[]}};
export type WikiLinkDto={pageId:string;title:string;communitySlug:string};
